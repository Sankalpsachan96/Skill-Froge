def evaluate_skill_answer(
    skill: str,
    question: str,
    options: list,
    correct_answer: int,
    student_answer: int,
    difficulty: str
):
    """
    AI evaluates the student's answer and provides
    an explanation and performance feedback.
    """

    selected_answer = ""

    if (
        isinstance(student_answer, int)
        and 0 <= student_answer < len(options)
    ):
        selected_answer = options[student_answer]


    correct_option = ""

    if (
        isinstance(correct_answer, int)
        and 0 <= correct_answer < len(options)
    ):
        correct_option = options[correct_answer]


    prompt = f"""
You are evaluating a student's skill verification test.

Skill:
{skill}

Difficulty:
{difficulty}

Question:
{question}

Options:
{json.dumps(options)}

Correct answer:
{correct_option}

Student's answer:
{selected_answer}

Determine whether the student demonstrated understanding.

Return ONLY valid JSON:

{{
    "correct": true,
    "score": 0,
    "explanation": "",
    "skill_level_signal": "",
    "feedback": ""
}}

Rules:

- correct must be true or false.
- score must be between 0 and 100.
- explanation must be short.
- skill_level_signal must be one of:
  "basic",
  "intermediate",
  "advanced"
- feedback should be useful to the student.
- Return ONLY JSON.
"""

    response = client.chat.completions.create(

        model="llama-3.3-70b-versatile",

        messages=[
            {
                "role": "system",
                "content":
                "You are an AI skill assessment evaluator."
            },
            {
                "role": "user",
                "content": prompt
            }
        ],

        temperature=0.2
    )

    ai_response = response.choices[0].message.content.strip()

    try:

        if ai_response.startswith("```"):
            ai_response = (
                ai_response
                .replace("```json", "")
                .replace("```", "")
                .strip()
            )

        return json.loads(ai_response)

    except json.JSONDecodeError:

        return {
            "error": "AI returned invalid JSON",
            "raw_response": ai_response
        }


