def calculate_skill_verification(
    skill: str,
    answers: list
):
    """
    Final AI-powered skill verification.

    The per-question scores are calculated during the test.
    Groq analyzes those scores and determines:
    - overall score
    - knowledge
    - problem solving
    - practical ability
    - skill level
    - AI confidence
    """

    if not answers:
        return {
            "error": "No answers were provided."
        }

    # --------------------------------------------------------
    # Calculate a reliable baseline from question evaluations
    # --------------------------------------------------------

    valid_scores = []

    for answer in answers:

        try:
            score = float(answer.get("score", 0))

            score = max(
                0,
                min(100, score)
            )

            valid_scores.append(score)

        except (TypeError, ValueError):
            continue


    if not valid_scores:
        return {
            "error": "No valid evaluation scores were found."
        }


    baseline_score = round(
        sum(valid_scores) / len(valid_scores)
    )


    correct_count = sum(
        1
        for answer in answers
        if answer.get("correct") is True
    )


    total_questions = len(answers)


    performance_summary = {
        "total_questions": total_questions,
        "correct_answers": correct_count,
        "question_scores": valid_scores,
        "baseline_score": baseline_score,
        "answers": answers
    }


    # --------------------------------------------------------
    # Ask Groq for final AI assessment
    # --------------------------------------------------------

    prompt = f"""
You are the final AI skill evaluator for
Student Skills Exchange.

The student claims they can teach:

SKILL:
{skill}

The student completed an adaptive AI verification test.

Here is the COMPLETE performance data:

{json.dumps(performance_summary, indent=2)}

IMPORTANT SCORING RULES:

1. The per-question "score" values are already calculated
   by the AI during the individual answer evaluations.

2. Use these scores as the primary evidence.

3. The baseline score is:
{baseline_score}

4. The final overall_score MUST normally be close to the
   baseline score.

5. NEVER return 0 for overall_score if valid question scores
   are available.

6. Only return 0 if there are genuinely no valid answers.

7. Do not arbitrarily give the student a perfect score.

8. Evaluate the student's actual performance.

9. Knowledge score should represent conceptual understanding.

10. Problem solving score should represent ability to apply
    knowledge and solve problems.

11. Practical score should represent real-world application.

12. Determine the level:

    Basic:
    approximately 0-59

    Intermediate:
    approximately 60-79

    Advanced:
    approximately 80-100

13. "verified" should be true when the student demonstrates
    sufficient ability to teach the claimed skill.

14. AI confidence should represent how confident you are
    in the assessment based on the available evidence.

Return ONLY valid JSON in exactly this structure:

{{
    "skill": "{skill}",
    "overall_score": 0,
    "knowledge_score": 0,
    "problem_solving_score": 0,
    "practical_score": 0,
    "level": "",
    "verified": false,
    "ai_confidence": 0,
    "strengths": [],
    "weaknesses": [],
    "summary": ""
}}

Rules:

- All scores must be integers from 0 to 100.
- overall_score should be based primarily on the
  question_scores.
- Do not return 0 when valid scores exist.
- level must be exactly:
  "Basic", "Intermediate", or "Advanced".
- strengths must be an array.
- weaknesses must be an array.
- summary must be short.
- Return ONLY JSON.
"""


    response = client.chat.completions.create(

        model="llama-3.3-70b-versatile",

        messages=[

            {
                "role": "system",
                "content":
                "You are a fair, rigorous AI skill certification evaluator."
            },

            {
                "role": "user",
                "content": prompt
            }

        ],

        temperature=0.1

    )


    ai_response = (
        response
        .choices[0]
        .message
        .content
        .strip()
    )


    try:

        # Remove markdown fences if Groq adds them

        if ai_response.startswith("```"):

            ai_response = (
                ai_response
                .replace("```json", "")
                .replace("```", "")
                .strip()
            )


        result = json.loads(
            ai_response
        )


        # ----------------------------------------------------
        # Safety normalization
        # ----------------------------------------------------

        def safe_score(value, fallback):

            try:

                value = int(
                    round(float(value))
                )

                if value < 0:
                    return 0

                if value > 100:
                    return 100

                return value

            except (
                TypeError,
                ValueError
            ):

                return fallback


        result["overall_score"] = safe_score(
            result.get("overall_score"),
            baseline_score
        )


        result["knowledge_score"] = safe_score(
            result.get("knowledge_score"),
            baseline_score
        )


        result["problem_solving_score"] = safe_score(
            result.get("problem_solving_score"),
            baseline_score
        )


        result["practical_score"] = safe_score(
            result.get("practical_score"),
            baseline_score
        )


        result["ai_confidence"] = safe_score(
            result.get("ai_confidence"),
            85
        )


        # ----------------------------------------------------
        # Prevent impossible 0 score
        # ----------------------------------------------------

        if baseline_score > 0:

            if result["overall_score"] == 0:

                result["overall_score"] = baseline_score


        # ----------------------------------------------------
        # Ensure valid level
        # ----------------------------------------------------

        level = result.get(
            "level",
            ""
        )


        if level not in [
            "Basic",
            "Intermediate",
            "Advanced"
        ]:

            if result["overall_score"] >= 80:

                level = "Advanced"

            elif result["overall_score"] >= 60:

                level = "Intermediate"

            else:

                level = "Basic"


        result["level"] = level


        # ----------------------------------------------------
        # Verification decision
        # ----------------------------------------------------

        result["verified"] = (
            result["overall_score"] >= 70
        )


        return result


    except json.JSONDecodeError:

        # ----------------------------------------------------
        # Fallback if Groq returns malformed JSON
        # ----------------------------------------------------

        if baseline_score >= 80:

            level = "Advanced"

        elif baseline_score >= 60:

            level = "Intermediate"

        else:

            level = "Basic"


        return {

            "skill": skill,

            "overall_score":
                baseline_score,

            "knowledge_score":
                baseline_score,

            "problem_solving_score":
                baseline_score,

            "practical_score":
                baseline_score,

            "level":
                level,

            "verified":
                baseline_score >= 70,

            "ai_confidence":
                80,

            "strengths": [],

            "weaknesses": [],

            "summary":
                "Assessment completed using AI-evaluated question performance.",

            "raw_response":
                ai_response

        }