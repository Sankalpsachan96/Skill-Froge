import os
import json

from dotenv import load_dotenv
from groq import Groq


# Load .env
load_dotenv()

# Get API key
api_key = os.getenv("GROQ_API_KEY")

if not api_key:
    raise RuntimeError("GROQ_API_KEY not found in .env")

# Create Groq client
client = Groq(api_key=api_key)


